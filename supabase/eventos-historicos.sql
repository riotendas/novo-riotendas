-- RioTendas - Base antiga de eventos (somente consulta)
-- 1) Execute este SQL no SQL Editor do Supabase.
-- 2) Depois importe o CSV riotendas-base-antiga-importacao.csv nesta tabela.
-- Esta tabela é independente de eventos/clientes/produtos/financeiro atuais.

create extension if not exists pg_trgm;
create extension if not exists unaccent;

create table if not exists public.eventos_historicos (
  id bigint generated by default as identity primary key,
  data_evento date,
  horario text,
  montagem text,
  desmontagem text,
  colaborador text,
  cliente text,
  contatos text,
  endereco text,
  descricao_servico text,
  valor_total text,
  sinal text,
  restante text,
  forma_pagamento text,
  cpf_cnpj text,
  busca_normalizada text not null default '',
  criado_em timestamptz not null default now()
);

create index if not exists idx_eventos_historicos_data
  on public.eventos_historicos (data_evento desc);

create index if not exists idx_eventos_historicos_busca_trgm
  on public.eventos_historicos using gin (busca_normalizada gin_trgm_ops);

alter table public.eventos_historicos enable row level security;

drop policy if exists "eventos_historicos_select" on public.eventos_historicos;
create policy "eventos_historicos_select"
on public.eventos_historicos
for select
to anon, authenticated
using (true);

-- Sem políticas de insert/update/delete para o aplicativo:
-- a base antiga fica somente para consulta.

create or replace function public.buscar_eventos_historicos(
  p_busca text default '',
  p_ano integer default null,
  p_limite integer default 50,
  p_offset integer default 0
)
returns table (
  id bigint,
  data_evento date,
  horario text,
  montagem text,
  desmontagem text,
  colaborador text,
  cliente text,
  contatos text,
  endereco text,
  descricao_servico text,
  valor_total text,
  sinal text,
  restante text,
  forma_pagamento text,
  cpf_cnpj text,
  total_encontrado bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with parametros as (
    select lower(unaccent(trim(coalesce(p_busca,'')))) as q
  ),
  filtrados as (
    select h.*
    from public.eventos_historicos h, parametros p
    where
      (p.q = '' or h.busca_normalizada ilike '%' || p.q || '%')
      and (p_ano is null or extract(year from h.data_evento)::integer = p_ano)
  )
  select
    f.id, f.data_evento, f.horario, f.montagem, f.desmontagem, f.colaborador,
    f.cliente, f.contatos, f.endereco, f.descricao_servico,
    f.valor_total, f.sinal, f.restante, f.forma_pagamento, f.cpf_cnpj,
    count(*) over() as total_encontrado
  from filtrados f
  order by f.data_evento desc nulls last, f.id desc
  limit greatest(1, least(coalesce(p_limite,50),100))
  offset greatest(coalesce(p_offset,0),0);
$$;

grant execute on function public.buscar_eventos_historicos(text,integer,integer,integer)
to anon, authenticated;
